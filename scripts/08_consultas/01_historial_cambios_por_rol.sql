USE PROYECTOFACTURACION;
GO

DECLARE @correo VARCHAR(150);
DECLARE @distrito INT;
DECLARE @senas VARCHAR(250);
DECLARE @telefono VARCHAR(20);
DECLARE @cod INT;
DECLARE @msg VARCHAR(250);
DECLARE @filas INT;
DECLARE @demo TABLE (
    ORDEN INT IDENTITY (1, 1),
    USUARIO VARCHAR(30),
    ROL VARCHAR(30),
    FILAS_VISIBLES VARCHAR(30)
);

BEGIN TRANSACTION;

SELECT
    @correo = CORREO,
    @distrito = DISTRITO_ID,
    @senas = OTRAS_SENAS,
    @telefono = CASE
        WHEN TELEFONO = '88887777' THEN '88886666'
        ELSE '88887777'
    END
FROM DBO.CLIENTE
WHERE CLIENTE_ID = 1;

EXEC DBO.USP_ACTUALIZAR_CLIENTE
    @cliente_id = 1,
    @correo = @correo,
    @telefono = @telefono,
    @distrito_id = @distrito,
    @otras_senas = @senas,
    @codigo_error = @cod OUTPUT,
    @mensaje_error = @msg OUTPUT;

IF @cod <> 0
    BEGIN
        IF @@TRANCOUNT > 0
            BEGIN
                ROLLBACK TRANSACTION;
            END

        RAISERROR ('No se pudo generar el cambio de prueba: %s', 16, 1, @msg);
        RETURN;
    END

SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES ('ADMINISTRADOR ACTUAL', 'db_owner', CAST(@filas AS VARCHAR(30)));

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_AUDITOR';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_AUDITOR', 'ROL_AUDITOR',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_DBA';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_DBA', 'ROL_DBA',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_ADMIN';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_ADMIN', 'ROL_ADMINISTRATIVO',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_CAJERO';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_CAJERO', 'ROL_CAJERO',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_CONSULTA';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_CONSULTA', 'ROL_CONSULTA',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SET @filas = NULL;
BEGIN TRY
    EXECUTE AS USER = 'USR_SIN_ROL';
    SET @filas = (SELECT COUNT(*) FROM DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS());
END TRY
BEGIN CATCH
    SET @filas = NULL;
END CATCH
REVERT;
INSERT INTO @demo (USUARIO, ROL, FILAS_VISIBLES)
VALUES (
    'USR_SIN_ROL', '(ninguno)',
    ISNULL(CAST(@filas AS VARCHAR(30)), 'SIN PERMISO')
);

SELECT
    USUARIO,
    ROL,
    FILAS_VISIBLES
FROM @demo
ORDER BY ORDEN;

ROLLBACK TRANSACTION;
GO
