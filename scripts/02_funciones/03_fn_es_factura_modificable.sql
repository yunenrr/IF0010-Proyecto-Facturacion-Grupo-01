USE PROYECTOFACTURACION;
GO

DROP FUNCTION IF EXISTS DBO.FN_ES_FACTURA_MODIFICABLE;
GO

CREATE FUNCTION DBO.FN_ES_FACTURA_MODIFICABLE (@numero_factura VARCHAR(50))
RETURNS BIT
AS
BEGIN
    DECLARE @modificable BIT = 0;

    SELECT @modificable = 1
    FROM DBO.FACTURA AS F
    INNER JOIN DBO.ESTADOFACTURA AS E
        ON F.ESTADO_FACTURA_ID = E.ESTADO_FACTURA_ID
    WHERE
        F.NUMERO_FACTURA = @numero_factura
        AND E.CODIGO = 'BORRADOR';

    RETURN @modificable;
END;
GO
