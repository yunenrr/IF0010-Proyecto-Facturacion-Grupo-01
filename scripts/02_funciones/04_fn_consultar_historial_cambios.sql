USE PROYECTOFACTURACION;
GO

DROP FUNCTION IF EXISTS DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS;
GO

CREATE FUNCTION DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS ()
RETURNS TABLE
AS
RETURN (
    SELECT
        A.AUDITORIA_ID,
        EN.NOMBRE AS ENTIDAD,
        A.REGISTRO_ID,
        OP.DESCRIPCION AS OPERACION,
        A.USUARIO,
        A.FECHA_CAMBIO,
        A.DESCRIPCION,
        A.DATOS_ANTERIORES,
        A.DATOS_NUEVOS
    FROM DBO.AUDITORIA AS A
    INNER JOIN DBO.ENTIDAD_AUDITADA AS EN
        ON A.ENTIDAD_AUDITADA_ID = EN.ENTIDAD_AUDITADA_ID
    INNER JOIN DBO.TIPO_OPERACION AS OP
        ON A.TIPO_OPERACION_ID = OP.TIPO_OPERACION_ID
    WHERE
        IS_MEMBER('ROL_AUDITOR') = 1
        OR IS_MEMBER('ROL_DBA') = 1
        OR IS_MEMBER('db_owner') = 1
);
GO

GRANT SELECT ON DBO.FN_CONSULTAR_HISTORIAL_CAMBIOS
TO ROL_AUDITOR, ROL_DBA, ROL_ADMINISTRATIVO, ROL_CAJERO, ROL_CONSULTA;
GO
