    DESCRIPCION VARCHAR(100) NOT NULL,

    CONSTRAINT PK_MONEDA
    PRIMARY KEY (MONEDA_ID),

    CONSTRAINT UQ_MONEDA_CODIGO
    UNIQUE (CODIGO)
);
GO
