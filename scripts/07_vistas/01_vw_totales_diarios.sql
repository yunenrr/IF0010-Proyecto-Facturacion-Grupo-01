USE PROYECTOFACTURACION;
GO

DROP VIEW IF EXISTS DBO.VW_TOTALES_DIARIOS;
GO

CREATE VIEW DBO.VW_TOTALES_DIARIOS
AS
SELECT
    CAST(F.FECHA_EMISION AS DATE) AS [FechaEmision],
    EM.NOMBRE_COMERCIAL AS [NombreEmpresa],
    TD.DESCRIPCION AS [TipoDocumento],
    COUNT(*) AS [CantidadFacturas],
    SUM(F.MONTO_SUBTOTAL) AS [SubtotalAcumulado],
    SUM(F.MONTO_DESCUENTO) AS [TotalDescuentos],
    SUM(F.MONTO_IMPUESTO) AS [TotalImpuestos],
    SUM(F.MONTO_TOTAL) AS [MontoTotalFacturado]
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESAEMISORA AS EM
    ON F.EMPRESA_ID = EM.EMPRESA_ID
INNER JOIN DBO.TIPODOCUMENTO AS TD
    ON F.TIPO_DOCUMENTO_ID = TD.TIPO_DOCUMENTO_ID
GROUP BY
    CAST(F.FECHA_EMISION AS DATE),
    EM.EMPRESA_ID,
    EM.NOMBRE_COMERCIAL,
    TD.TIPO_DOCUMENTO_ID,
    TD.DESCRIPCION;
GO
