USE PROYECTOFACTURACION;
GO

DECLARE @inicio DATETIME2 = SYSDATETIME();
DECLARE @nombre_comercial VARCHAR(150);

SELECT TOP (1) @nombre_comercial = NOMBRE_COMERCIAL
FROM DBO.CLIENTE_JURIDICO
ORDER BY CLIENTE_ID;

SELECT
    CL.IDENTIFICACION AS CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    CL.CORREO,
    CL.TELEFONO
FROM DBO.CLIENTE_JURIDICO AS CJ
INNER JOIN DBO.CLIENTE AS CL
    ON CJ.CLIENTE_ID = CL.CLIENTE_ID
WHERE CJ.NOMBRE_COMERCIAL = @nombre_comercial
ORDER BY CL.IDENTIFICACION;

SELECT DATEDIFF(MILLISECOND, @inicio, SYSDATETIME()) AS MILISEGUNDOS;
GO
