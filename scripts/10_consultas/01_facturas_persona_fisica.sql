USE PROYECTOFACTURACION;
GO

DECLARE @inicio DATETIME2 = SYSDATETIME();
DECLARE @cedula VARCHAR(20) = (
    SELECT TOP (1) CL.IDENTIFICACION
    FROM DBO.CLIENTE AS CL
    INNER JOIN DBO.CLIENTE_FISICO AS CF
        ON CL.CLIENTE_ID = CF.CLIENTE_ID
    WHERE EXISTS (
        SELECT 1
        FROM DBO.FACTURA AS FX
        WHERE FX.CLIENTE_ID = CL.CLIENTE_ID
    )
    ORDER BY CL.CLIENTE_ID
);

SELECT
    CL.IDENTIFICACION AS CEDULA,
    CONCAT(CF.NOMBRE, ' ', CF.APELLIDO1, ' ', CF.APELLIDO2) AS CLIENTE,
    F.NUMERO_FACTURA,
    F.FECHA_EMISION,
    TD.DESCRIPCION AS TIPO_DOCUMENTO,
    EM.NOMBRE_COMERCIAL AS EMPRESA,
    MO.CODIGO AS MONEDA,
    ES.CODIGO AS ESTADO,
    F.TIPO_CAMBIO,
    F.MONTO_SUBTOTAL,
    F.MONTO_DESCUENTO,
    F.MONTO_IMPUESTO,
    F.MONTO_TOTAL,
    F.OBSERVACIONES
FROM DBO.CLIENTE AS CL
INNER JOIN DBO.CLIENTE_FISICO AS CF
    ON CL.CLIENTE_ID = CF.CLIENTE_ID
INNER JOIN DBO.FACTURA AS F
    ON CL.CLIENTE_ID = F.CLIENTE_ID
INNER JOIN DBO.TIPODOCUMENTO AS TD
    ON F.TIPO_DOCUMENTO_ID = TD.TIPO_DOCUMENTO_ID
INNER JOIN DBO.EMPRESAEMISORA AS EM
    ON F.EMPRESA_ID = EM.EMPRESA_ID
INNER JOIN DBO.MONEDA AS MO
    ON F.MONEDA_ID = MO.MONEDA_ID
INNER JOIN DBO.ESTADOFACTURA AS ES
    ON F.ESTADO_FACTURA_ID = ES.ESTADO_FACTURA_ID
WHERE CL.IDENTIFICACION = @cedula
ORDER BY F.FECHA_EMISION DESC;

SELECT DATEDIFF(MILLISECOND, @inicio, SYSDATETIME()) AS MILISEGUNDOS;
GO
