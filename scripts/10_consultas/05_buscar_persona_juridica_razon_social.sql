DECLARE @razon_social VARCHAR(150) = 'Comercial Chaves 10 Sociedad Anonima';

SELECT
    CL.IDENTIFICACION AS CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    CL.CORREO,
    CL.TELEFONO
FROM DBO.CLIENTE_JURIDICO AS CJ
INNER JOIN DBO.CLIENTE AS CL
    ON CJ.CLIENTE_ID = CL.CLIENTE_ID
WHERE CJ.RAZON_SOCIAL = @razon_social
ORDER BY CL.IDENTIFICACION;
GO
