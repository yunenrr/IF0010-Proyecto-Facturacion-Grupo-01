USE PROYECTOFACTURACION;
GO

DECLARE @cedula VARCHAR(20) = '100000001';
DECLARE @anio INT = YEAR(SYSDATETIME());
DECLARE @anio_inicio DATE = DATEFROMPARTS(@anio, 1, 1);
DECLARE @anio_fin DATE = DATEFROMPARTS(@anio + 1, 1, 1);

SELECT
    CL.IDENTIFICACION AS CEDULA,
    COUNT(F.FACTURA_ID) AS CANTIDAD_FACTURAS,
    ROUND(SUM(F.MONTO_DESCUENTO * F.TIPO_CAMBIO), 2) AS TOTAL_DESCUENTOS_CRC,
    ROUND(SUM(F.MONTO_IMPUESTO * F.TIPO_CAMBIO), 2) AS TOTAL_IMPUESTOS_CRC,
    ROUND(SUM(F.MONTO_TOTAL * F.TIPO_CAMBIO), 2) AS MONTO_TOTAL_FACTURADO_CRC
FROM DBO.CLIENTE AS CL
INNER JOIN DBO.FACTURA AS F
    ON CL.CLIENTE_ID = F.CLIENTE_ID
INNER JOIN DBO.ESTADOFACTURA AS ES
    ON F.ESTADO_FACTURA_ID = ES.ESTADO_FACTURA_ID
WHERE
    CL.IDENTIFICACION = @cedula
    AND ES.CODIGO IN ('EMITIDA', 'PAGADA')
    AND F.FECHA_EMISION >= @anio_inicio
    AND F.FECHA_EMISION < @anio_fin
GROUP BY CL.IDENTIFICACION;
GO
