USE PROYECTOFACTURACION;
GO

DECLARE @inicio DATETIME2 = SYSDATETIME();
DECLARE @nombre VARCHAR(50);
DECLARE @apellido1 VARCHAR(50);

SELECT TOP (1)
    @nombre = NOMBRE,
    @apellido1 = APELLIDO1
FROM DBO.CLIENTE_FISICO
ORDER BY CLIENTE_ID;

SELECT
    CL.IDENTIFICACION AS CEDULA,
    CF.NOMBRE,
    CF.APELLIDO1,
    CF.APELLIDO2,
    CL.CORREO,
    CL.TELEFONO
FROM DBO.CLIENTE_FISICO AS CF
INNER JOIN DBO.CLIENTE AS CL
    ON CF.CLIENTE_ID = CL.CLIENTE_ID
WHERE
    CF.NOMBRE = @nombre
    AND CF.APELLIDO1 = @apellido1
ORDER BY CL.IDENTIFICACION;

SELECT DATEDIFF(MILLISECOND, @inicio, SYSDATETIME()) AS MILISEGUNDOS;
GO
