USE PROYECTOFACTURACION;
GO

DECLARE @codigo_producto VARCHAR(30) = 'PROD-000001';
DECLARE @desde DATETIME2 = DATEADD(MONTH, -6, SYSDATETIME());
DECLARE @hasta DATETIME2 = SYSDATETIME();

SELECT
    F.FACTURA_ID,
    FD.CANTIDAD,
    F.FECHA_EMISION
FROM DBO.ITEM_FACTURABLE AS IT
INNER JOIN DBO.PRODUCTO_CON_EXISTENCIA AS PE
    ON IT.ITEM_FACTURABLE_ID = PE.PRODUCTO_CON_EXISTENCIA_ID
INNER JOIN DBO.FACTURA_DETALLE AS FD
    ON IT.ITEM_FACTURABLE_ID = FD.ITEM_FACTURABLE_ID
INNER JOIN DBO.FACTURA AS F
    ON FD.FACTURA_ID = F.FACTURA_ID
WHERE
    IT.CODIGO_INTERNO = @codigo_producto
    AND F.FECHA_EMISION >= @desde
    AND F.FECHA_EMISION <= @hasta
ORDER BY F.FECHA_EMISION;
GO
