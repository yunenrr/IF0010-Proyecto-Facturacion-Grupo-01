USE PROYECTOFACTURACION;
GO

DECLARE @nombre VARCHAR(50) = 'Laura';
DECLARE @apellido2 VARCHAR(50) = 'Esquivel';

SELECT
    CL.IDENTIFICACION AS CEDULA,
    CF.NOMBRE,
    CF.APELLIDO1,
    CF.APELLIDO2,
    CL.CORREO,
    CL.TELEFONO
FROM DBO.CLIENTE_FISICO AS CF
INNER JOIN DBO.CLIENTE AS CL
    ON CF.CLIENTE_ID = CL.CLIENTE_ID
WHERE
    CF.NOMBRE = @nombre
    AND CF.APELLIDO2 = @apellido2
ORDER BY CL.IDENTIFICACION;
GO
